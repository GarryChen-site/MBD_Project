function info = s4_02_generate_code()
%S4_02_GENERATE_CODE  Generate C code from ctrl_codegen.slx, copy snapshot to 04_firmware/app_generated,
%   generate 04_firmware/app_wrapper.{c,h} and prof.h, and audit generated C for double/malloc (A4-6, A4-7).
root = setup_paths();
par = init_params();
load_params_to_base(par);

mdl = 'ctrl_codegen';
mdlPath = fullfile(root, 'controller', [mdl '.slx']);
if ~isfile(mdlPath), s4_01_build_codegen_model(); end
if ~bdIsLoaded(mdl), load_system(mdlPath); end

% Generate code inside 03_simulink/codegen_work so workspace stays tidy
workDir = fullfile(root, 'codegen_work');
if ~exist(workDir, 'dir'), mkdir(workDir); end
oldDir = pwd;
cleanup = onCleanup(@() cd(oldDir));
cd(workDir);

slbuild(mdl);

% Locate generated folder (ctrl_codegen_ert_rtw or ctrl_codegen_grt_rtw)
d = dir(fullfile(workDir, [mdl '_*_rtw']));
assert(~isempty(d), 'Generated *_rtw folder not found in %s', workDir);
genSrcDir = fullfile(workDir, d(1).name);

% Copy clean snapshot of .c and .h files to 04_firmware/app_generated/
repoRoot = fileparts(root);
appGenDir = fullfile(repoRoot, '04_firmware', 'app_generated');
if exist(appGenDir, 'dir'), rmdir(appGenDir, 's'); end
mkdir(appGenDir);

cFiles = [dir(fullfile(genSrcDir, '*.c')); dir(fullfile(genSrcDir, '*.h'))];
for i = 1:numel(cFiles)
    % Skip rtw_proj.tmw orert_main if needed, but keep all .c/.h for complete snapshot
    copyfile(fullfile(genSrcDir, cFiles(i).name), fullfile(appGenDir, cFiles(i).name));
end

% Also check slprj/_sharedutils if any shared headers/sources were emitted
sharedDir = fullfile(workDir, 'slprj', 'ert', '_sharedutils');
if exist(sharedDir, 'dir')
    sFiles = [dir(fullfile(sharedDir, '*.c')); dir(fullfile(sharedDir, '*.h'))];
    for i = 1:numel(sFiles)
        copyfile(fullfile(sharedDir, sFiles(i).name), fullfile(appGenDir, sFiles(i).name));
    end
end

% Audit ctrl_codegen.c for dynamic memory (malloc/calloc/free) and double ops in step()
cFile = fullfile(appGenDir, [mdl '.c']);
codeTxt = fileread(cFile);
hasDynMem = ~isempty(regexp(codeTxt, '\<(malloc|calloc|realloc|free)\>', 'once'));

% Extract step function body to check for double (real_T) local variables
stepIdx = strfind(codeTxt, 'void ctrl_codegen_step(void)');
if ~isempty(stepIdx)
    stepBody = codeTxt(stepIdx(1):end);
else
    stepBody = codeTxt;
end
hasDoubleInStep = ~isempty(regexp(stepBody, '\<(double|real_T)\>', 'once'));

% Write 04_firmware/app_wrapper.h, app_wrapper.c, and prof.h
write_firmware_wrappers(fullfile(repoRoot, '04_firmware'));

info = struct('genDir', appGenDir, 'cFile', cFile, 'hasDynMem', hasDynMem, ...
              'hasDoubleInStep', hasDoubleInStep, 'numFiles', numel(cFiles));
fprintf('[S4-02] C code generated in %s (%d files) | dynMem=%d | doubleInStep=%d\n', ...
        appGenDir, numel(cFiles), hasDynMem, hasDoubleInStep);
end

function write_firmware_wrappers(fwDir)
% Write clean Rte_AppIn_t / Rte_AppOut_t wrapper and DWT profiler header per Stage 4 sections 4 & 6.
hdr = [ ...
'/* app_wrapper.h - Stage 4 clean boundary between BSW/RTE and Embedded Coder ctrl_codegen */', newline, ...
'#ifndef APP_WRAPPER_H', newline, ...
'#define APP_WRAPPER_H', newline, ...
'#include <stdint.h>', newline, ...
'#include <stdbool.h>', newline, newline, ...
'typedef struct {', newline, ...
'    float pedal1_adc;', newline, ...
'    float pedal2_adc;', newline, ...
'    float speed_meas_rpm;', newline, ...
'} Rte_AppIn_t;', newline, newline, ...
'typedef struct {', newline, ...
'    float    duty_cmd_pct;', newline, ...
'    float    speed_req_rpm;', newline, ...
'    uint16_t fault_bitmap;', newline, ...
'    uint8_t  mode;', newline, ...
'    float    s1_pct;', newline, ...
'    float    p2_pct;', newline, ...
'    float    e_pct;', newline, ...
'    float    p_cmd_pct;', newline, ...
'} Rte_AppOut_t;', newline, newline, ...
'void App_Init(void);', newline, ...
'void App_Step10ms(const Rte_AppIn_t *in, Rte_AppOut_t *out);', newline, ...
'#endif /* APP_WRAPPER_H */', newline];

src = [ ...
'/* app_wrapper.c - Stage 4 wrapper calling generated ctrl_codegen_step() */', newline, ...
'#include <string.h>', newline, ...
'#include "app_wrapper.h"', newline, ...
'#include "app_generated/ctrl_codegen.h"', newline, newline, ...
'void App_Init(void) {', newline, ...
'    memset(&ctrl_codegen_DW, 0, sizeof(ctrl_codegen_DW));', newline, ...
'    memset(&ctrl_codegen_U,  0, sizeof(ctrl_codegen_U));', newline, ...
'    memset(&ctrl_codegen_Y,  0, sizeof(ctrl_codegen_Y));', newline, ...
'    ctrl_codegen_initialize();', newline, ...
'}', newline, newline, ...
'void App_Step10ms(const Rte_AppIn_t *in, Rte_AppOut_t *out) {', newline, ...
'    ctrl_codegen_U.pedal1_adc     = in->pedal1_adc;', newline, ...
'    ctrl_codegen_U.pedal2_adc     = in->pedal2_adc;', newline, ...
'    ctrl_codegen_U.speed_meas_rpm = in->speed_meas_rpm;', newline, ...
'    ctrl_codegen_step();', newline, ...
'    out->duty_cmd_pct  = ctrl_codegen_Y.duty_cmd_pct;', newline, ...
'    out->speed_req_rpm = ctrl_codegen_Y.speed_req_rpm;', newline, ...
'    out->fault_bitmap  = ctrl_codegen_Y.fault_bitmap;', newline, ...
'    out->mode          = ctrl_codegen_Y.mode;', newline, ...
'    out->s1_pct        = ctrl_codegen_Y.s1_pct;', newline, ...
'    out->p2_pct        = ctrl_codegen_Y.p2_pct;', newline, ...
'    out->e_pct         = ctrl_codegen_Y.e_pct;', newline, ...
'    out->p_cmd_pct     = ctrl_codegen_Y.p_cmd_pct;', newline, ...
'}', newline];

prof = [ ...
'/* prof.h - Stage 4 section 6 ARM Cortex-M4 DWT cycle-counter WCET profiler */', newline, ...
'#ifndef PROF_H', newline, ...
'#define PROF_H', newline, ...
'#include <stdint.h>', newline, ...
'#ifdef STM32F446xx', newline, ...
'#include "stm32f4xx.h"', newline, ...
'static inline void Prof_Init(void) {', newline, ...
'    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;', newline, ...
'    DWT->CYCCNT = 0u;', newline, ...
'    DWT->CTRL  |= DWT_CTRL_CYCCNTENA_Msk;', newline, ...
'}', newline, ...
'static inline uint32_t Prof_Now(void) { return DWT->CYCCNT; }', newline, ...
'static inline uint32_t Prof_CyclesToUs(uint32_t cycles) { return cycles / (SystemCoreClock / 1000000u); }', newline, ...
'#endif', newline, ...
'#endif /* PROF_H */', newline];

fid = fopen(fullfile(fwDir, 'app_wrapper.h'), 'w'); fwrite(fid, hdr); fclose(fid);
fid = fopen(fullfile(fwDir, 'app_wrapper.c'), 'w'); fwrite(fid, src); fclose(fid);
fid = fopen(fullfile(fwDir, 'prof.h'), 'w');        fwrite(fid, prof); fclose(fid);
end
